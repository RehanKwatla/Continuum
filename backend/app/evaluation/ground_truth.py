"""Synthetic ground-truth dataset (Phase 5 §9).

This module describes, declaratively, what a *correct* Continuum pipeline should
produce for one synthetic project. It is stored **separately from the system's
extracted outputs**: nothing here is generated by a model, and the evaluation
metrics read the real database state back and score it against these
expectations.

The synthetic project is the "Payments Service" handover dataset — the same
shape as ``tests/synthetic_project.py`` but authored here as a product-owned
reference dataset so the evaluation is a real, shippable feature rather than a
test-only helper. It deliberately contains:

* several artefacts (a markdown document, a commit, a README, an issue);
* a **contradiction** (two sources disagree about the database version);
* an **ownership change over time** (Alice → Bob, which is *not* a contradiction);
* **stale information** (a README a newer commit has since changed);
* a **restricted** source a successor must never see;
* **deliberately missing knowledge** (no rollback, incident or decision records).

Nothing in this file is a promise that the live model will find these facts — it
is the yardstick the live model is measured against.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from app.models.enums import ClaimType, RequirementCompletion

#: Bumped whenever the expectations below change, so runs stay comparable.
GROUND_TRUTH_VERSION = "continuum-ground-truth-v1"

#: The project name the synthetic dataset is seeded under.
GROUND_TRUTH_PROJECT_NAME = "Payments Service Handover (ground truth)"


@dataclass(frozen=True)
class GroundTruthClaim:
    """One fact a correct pipeline should extract, with its provenance."""

    key: str
    text: str
    claim_type: ClaimType
    #: Tokens that must appear (case-insensitively) in a claim for it to match.
    keywords: tuple[str, ...]
    #: ``source_name`` of the source the claim must cite as evidence.
    evidence_source: str
    entity: str | None = None
    critical: bool = False
    #: Whether a human should be able to approve this claim as evidence-backed.
    approvable: bool = True
    #: The verification verdict a correct verifier should reach.
    expected_verdict: str = "supports"


@dataclass(frozen=True)
class GroundTruthConflict:
    """Two ground-truth claims that disagree about the same property."""

    left: str
    right: str
    property_key: str
    kind: str = "value_disagreement"


@dataclass(frozen=True)
class GroundTruthGap:
    """Knowledge the dataset deliberately withholds."""

    requirement_id: str
    category: str
    description: str


@dataclass(frozen=True)
class GroundTruthDataset:
    version: str
    project_name: str
    claims: tuple[GroundTruthClaim, ...]
    conflicts: tuple[GroundTruthConflict, ...]
    #: Sources that a correct staleness detector should flag.
    stale_sources: tuple[str, ...]
    #: A source that must never appear in a successor-facing evidence index.
    restricted_source: str | None
    missing_knowledge: tuple[GroundTruthGap, ...]
    #: Human-labelled readiness expectations used by the agreement metric.
    readiness_expectations: dict[str, RequirementCompletion] = field(default_factory=dict)

    def claim(self, key: str) -> GroundTruthClaim:
        for item in self.claims:
            if item.key == key:
                return item
        raise KeyError(key)


